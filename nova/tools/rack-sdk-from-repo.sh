#!/usr/bin/env bash
# Assembles a folder laid out like the Rack 2 SDK from what this repository
# already has, so nova/plugin builds for desktop VCV Rack without downloading
# the SDK:
#
#   nova/tools/rack-sdk-from-repo.sh [out-dir]      (default nova/downloads/rack-sdk)
#   make -C nova/plugin RACK_DIR="$PWD/nova/downloads/rack-sdk" install
#
# What goes in:
#   include/       Rack 2.6.4's own headers (third_party/Rack/include)
#   dep/include/   the headers Rack's include: NanoVG, NanoSVG, GLFW, pffft,
#                  simde, speexdsp, blendish, and Jansson
#   *.mk           Rack's plugin build rules
#   libRack.dylib  from the installed VCV Rack 2 (macOS), to link against
#
# Jansson's headers are generated by its build, so they come from an Android
# build of this repository (app/.cxx/...): run ./gradlew assemble... once first.
# Headers only describe the ABI of the Rack that loads the plugin; Rack 2.x
# keeps that stable, so a plugin built this way loads in any Rack 2.
set -euo pipefail
cd "$(dirname "$0")/../.."

OUT="${1:-nova/downloads/rack-sdk}"
RACK=third_party/Rack
DEP="$RACK/dep"

JANSSON=$(ls -d app/.cxx/*/*/*/_deps/jansson-build/include 2>/dev/null | head -1 || true)
if [ -z "$JANSSON" ] || [ ! -f "$JANSSON/jansson.h" ]; then
	echo "Jansson headers not found under app/.cxx: build the app once first" >&2
	echo "  ./gradlew assembleSideloadRelease -PdevKeystore -PtestBuild" >&2
	exit 1
fi

rm -rf "$OUT"
mkdir -p "$OUT/dep/include/GL" "$OUT/dep/include/speex"

cp -R "$RACK/include" "$OUT/include"
cp "$RACK/plugin.mk" "$RACK/arch.mk" "$RACK/compile.mk" "$RACK/dep.mk" "$OUT/"

I="$OUT/dep/include"
cp "$JANSSON/jansson.h" "$JANSSON/jansson_config.h" "$I/"
cp "$DEP"/nanovg/src/*.h "$I/"
cp "$DEP"/nanosvg/src/nanosvg.h "$DEP"/nanosvg/src/nanosvgrast.h "$I/"
cp -R "$DEP/glfw/include/GLFW" "$I/GLFW"
cp "$DEP"/pffft/pffft.h "$I/"
cp -R "$DEP/simde/simde" "$I/simde"
cp "$DEP"/oui-blendish/blendish.h "$DEP"/oui-blendish/oui.h "$I/"
cp "$DEP"/speexdsp/include/speex/*.h "$I/speex/"
# speexdsp_config_types.h is generated by speexdsp's configure; the template
# only needs the four fixed-width types filled in.
sed -e 's/@INCLUDE_STDINT@/#include <stdint.h>/' \
	-e 's/@SIZE16@/int16_t/' -e 's/@USIZE16@/uint16_t/' \
	-e 's/@SIZE32@/int32_t/' -e 's/@USIZE32@/uint32_t/' \
	"$DEP/speexdsp/include/speex/speexdsp_config_types.h.in" > "$I/speex/speexdsp_config_types.h"

# Rack's Window.hpp includes GLEW for the GL types alone. The plugin never
# calls GL, so the platform's own header (or the bare typedefs) will do.
cat > "$I/GL/glew.h" <<'EOF'
#pragma once
#if defined(__APPLE__)
	#define GL_SILENCE_DEPRECATION 1
	#include <OpenGL/gl.h>
#elif defined(__has_include) && __has_include(<GL/gl.h>)
	#include <GL/gl.h>
#else
	typedef unsigned int GLenum;
	typedef unsigned int GLuint;
	typedef int GLint;
	typedef int GLsizei;
	typedef float GLfloat;
	typedef unsigned char GLubyte;
	typedef unsigned char GLboolean;
	typedef unsigned int GLbitfield;
#endif
EOF

case "$(uname -s)" in
	Darwin)
		LIB=$(ls -d /Applications/VCV\ Rack\ 2*.app/Contents/Resources/libRack.dylib 2>/dev/null | head -1 || true)
		if [ -z "$LIB" ]; then
			echo "VCV Rack 2 is not installed in /Applications: no libRack.dylib to link against" >&2
			exit 1
		fi
		cp "$LIB" "$OUT/libRack.dylib"
		;;
	*)
		echo "note: copy libRack.so (or libRack.dll.a) from your Rack install into $OUT" >&2
		;;
esac

echo "Rack SDK assembled in $OUT"
